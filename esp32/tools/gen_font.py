#!/usr/bin/env python3
"""Generate main/esp_font8x16.h (printable ASCII, 8x16 bitmap) from a PSF1/PSF2 console font.

  tools/gen_font.py /etc/console-setup/Uni2-Fixed16.psf.gz > main/esp_font8x16.h

Uni2-Fixed16 is the public-domain "misc-fixed" family. Only the 95 printable ASCII glyphs are kept, so
the table is 1520 bytes. Row 0 is the top row, bit 7 (0x80) is the leftmost pixel.
"""
import gzip
import struct
import sys


def load(path):
    data = open(path, "rb").read()
    if data[:2] == b"\x1f\x8b":
        data = gzip.decompress(data)
    if data[:2] == b"\x36\x04":  # PSF1
        mode, height = data[2], data[3]
        count = 512 if mode & 1 else 256
        hdr = 4
        unicode_table = bool(mode & 6)
        glyphs = [data[hdr + i * height: hdr + (i + 1) * height] for i in range(count)]
        # PSF1 maps glyph i to code i unless a unicode table exists; the first 128 are ASCII in practice
        return glyphs, height, 8
    if data[:4] == b"\x72\xb5\x4a\x86":  # PSF2
        (_, _, hdrsize, flags, length, charsize, height, width) = struct.unpack("<8I", data[:32])
        if width != 8:
            sys.exit("font is %d pixels wide, need 8" % width)
        glyphs = [data[hdrsize + i * charsize: hdrsize + (i + 1) * charsize] for i in range(length)]
        return glyphs, height, width
    sys.exit("not a PSF font")


def main():
    glyphs, height, width = load(sys.argv[1])
    if height != 16:
        sys.exit("font is %d rows high, need 16" % height)
    print("/* Generated by tools/gen_font.py from %s: ASCII 0x20..0x7E, 8x16, bit 7 = leftmost pixel. */" % sys.argv[1].split("/")[-1])
    print("#pragma once")
    print("#include <stdint.h>")
    print("static const uint8_t esp_font8x16[95][16] = {")
    for c in range(0x20, 0x7F):
        g = glyphs[c]
        print("    {%s}, /* '%s' */" % (", ".join("0x%02x" % b for b in g), chr(c).replace("\\", "\\\\").replace("*/", "* /")))
    print("};")


main()
